// content.json -> content.js (file:// 에서 fetch 없이 오프라인 실행하기 위함)
import { readFileSync, writeFileSync } from 'node:fs';
const src = new URL('../src/content.json', import.meta.url);
const out = new URL('../src/content.js', import.meta.url);
const data = JSON.parse(readFileSync(src, 'utf8'));
writeFileSync(out, '// generated by tools/build-content.mjs — edit content.json instead\nwindow.CONTENT = ' + JSON.stringify(data, null, 2) + ';\n');
console.log('wrote src/content.js');
